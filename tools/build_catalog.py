"""Generate datasets/examples/*.csv and datasets/catalog/catalog.json.

The only dataset shipped is synthetic and says so in its kind, description and limitations.
No measured or public dataset is included, and none is claimed.
"""

from __future__ import annotations

import hashlib

import numpy as np
import pandas as pd
import registry as R

from control_lab.models import BeltConveyor

SEED = 20261125
TS = 0.01
DATA = R.ROOT / "datasets"


def conveyor_step_test() -> pd.DataFrame:
    """Open-loop step test on the conveyor model with measurement noise and encoder quantisation."""
    rng = np.random.default_rng(SEED)
    plant = BeltConveyor(Ts=TS, substeps=5, m_payload=10.0)
    u_lo, u_hi = 0.30, 0.45
    n = 600
    t = np.arange(n) * TS
    u = np.where(t < 1.0, u_lo, u_hi)
    v_true = np.empty(n)
    for k in range(n):
        v_true[k] = plant.step(float(u[k]))
    quant = 0.002
    v_meas = np.round((v_true + rng.normal(0.0, 0.003, n)) / quant) * quant
    return pd.DataFrame({"t_s": t, "u_cmd": u, "v_true_m_s": v_true, "v_meas_m_s": v_meas})


def main():
    df = conveyor_step_test()
    path = DATA / "examples" / "conveyor_step_test_synthetic.csv"
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False, float_format="%.6g")
    sha = hashlib.sha256(path.read_bytes()).hexdigest()
    entry = dict(
        id="ds_conveyor_step_synthetic",
        name="Conveyor open-loop step test (synthetic)",
        kind="synthetic_illustrative",
        description="Open-loop command step 0.30 to 0.45 at t = 1 s on the BeltConveyor model with a "
                    "10 kg payload. The measured speed adds Gaussian noise and encoder quantisation to "
                    "the true simulated speed. Generated, not measured.",
        origin="control_lab.models.BeltConveyor via tools/build_catalog.py",
        generator="tools/build_catalog.py", seed=SEED,
        file="datasets/examples/conveyor_step_test_synthetic.csv", license="MIT (generated by this repository)",
        sampling_time_s=TS, n_rows=int(len(df)),
        columns=[
            dict(name="t_s", unit="s", description="Time since start"),
            dict(name="u_cmd", unit="1 (0 to 1)", description="Normalised drive command"),
            dict(name="v_true_m_s", unit="m/s", description="Simulated belt speed before the sensor. "
                 "A real experiment would not have this column."),
            dict(name="v_meas_m_s", unit="m/s", description="Belt speed with noise (sigma 0.003 m/s) and "
                 "0.002 m/s quantisation"),
        ],
        limitations=["Synthetic: the plant model and the noise model are assumptions of this repository.",
                     "Illustrative parameters, not identified from a conveyor.",
                     "Identification quality on this file says nothing about identification on real data."],
        used_by=[], sha256=sha)
    catalog = dict(
        schema_version="1.0",
        notice="No measured and no public dataset is included. Entries with kind synthetic_illustrative "
               "are generated by code in this repository.",
        datasets=[entry],
        candidates_not_included=[
            dict(topic="Project 14 (motor condition monitoring)",
                 note="Needs real or public current, temperature and vibration recordings. None was "
                      "located and verified, so none is listed.")])
    R.write_json(DATA / "catalog" / "catalog.json", catalog)
    print("catalog:", entry["id"], entry["n_rows"], "rows", sha[:12])


if __name__ == "__main__":
    main()
