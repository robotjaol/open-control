HEADER = ("<!-- Generated by tools/build_research.py. Edit tools/refs.py or the notebook specs, "
          "then rebuild. -->\n\n")


def write(rel: str, text: str) -> None:
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER + text.rstrip() + "\n")


def num(x, nd=3):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, float)):
        return f"{x:.{nd}g}"
    return str(x)


def table(rows, cols, heads=None):
    heads = heads or cols
    lines = ["| " + " | ".join(heads) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(num(r.get(c)) for c in cols) + " |")
    return "\n".join(lines)


STATUS_LEGEND = (
    "Verification status: **verified** = authors, year, title and venue (volume, pages or ISBN) were "
    "found on at least one publisher, index or library record. **partial** = the record was found "
    "but a stated field could not be confirmed (see the note). No reference was verified by reading "
    "its full text, and Crossref's API was unreachable from the build environment, so DOI "
    "resolution was not machine-checked.\n")


def source_register(metas):
    used = {}
    for m in metas:
        for k in m.get("refs", []):
            used.setdefault(k, []).append(m["number"])
    lines = ["# Source register\n", STATUS_LEGEND,
             "| Key | Citation | Status | Used in notebooks | Role in this repository | Limitation | Evidence |",
             "|---|---|---|---|---|---|---|"]
    for k, r in refs.REFS.items():
        v = r["verification"]
        lines.append(f"| {k} | {refs.cite(k)} | {v['status']} ({v['checked']}) | "
                     f"{', '.join(used.get(k, [])) or 'none'} | {r['role']} | {r['limits']} | "
                     f"{v['evidence_url']} - {v['note']} |")
    lines.append(f"\nTotal: {len(refs.REFS)} references, "
                 f"{sum(1 for r in refs.REFS.values() if r['verification']['status'] == 'verified')} verified, "
                 f"{sum(1 for r in refs.REFS.values() if r['verification']['status'] != 'verified')} partial.")
    lines.append("\nOldest year: %d. Newest year: %d. There is no reference from 2022 onward."
                 % (min(r["year"] for r in refs.REFS.values()), max(r["year"] for r in refs.REFS.values())))
    write("source-register.md", "\n".join(lines))


