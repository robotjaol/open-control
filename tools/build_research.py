def reviews():
    idx = ["# Literature review index\n",
           "Each page lists the sources behind one cluster of notebooks, what each source is used for, "
           "and what was measured here. These are source inventories with stated limits, not "
           "systematic reviews. No search of post-2021 literature was made, so recent work is absent.\n"]
    for fname, (title, keys, nbs, exp) in REVIEWS.items():
        lines = [f"# {title}\n", f"Notebooks: {nbs}. Primary experiment file: `{exp}`.\n",
                 "| Source | Status | Role | Limit |", "|---|---|---|---|"]
        for k in keys:
            r = refs.REFS[k]
            lines.append(f"| {refs.cite(k)} | {r['verification']['status']} | {r['role']} | {r['limits']} |")
        res = R.load_result(exp)
        lines += ["\n## Limitations recorded in the experiment\n"] + [f"- {x}" for x in res["limitations"]]
        write(f"literature-review/{fname}", "\n".join(lines))
        idx.append(f"- [{title}]({fname})")
    write("literature-review/README.md", "\n".join(idx))


def gaps_and_cases():
    lim = {}
    for m in R.load_metas():
        for exp in m["experiments"]:
            for x in R.load_result(exp)["limitations"]:
                lim.setdefault(x, []).append(exp)
    shared = sorted(lim.items(), key=lambda kv: (-len(kv[1]), kv[0]))
    rows = R.topic_counts(__import__("taxonomy").topic_rows())
    lines = ["# Research gaps\n",
             "## Gaps in this repository's evidence base\n",
             "- No experiment used measured data or hardware. Every result is a simulation of an "
             "illustrative plant.",
             f"- {rows.get('Planned', 0)} of {sum(rows.values())} taxonomy topics are Planned (no content).",
             "- No literature from 2022 onward is registered; the search was not performed.",
             "- Standards were checked at catalogue level only.\n",
             "## Unverified candidates\n"]
    lines += [f"- **{a}**. {b}" for a, b in refs.UNVERIFIED_CANDIDATES]
    lines += ["\n## Limitations repeated across experiments\n"]
    lines += [f"- {txt} ({', '.join(e.replace('exp_', '')[:2] for e in ex)})" for txt, ex in shared if len(ex) > 1]
    write("research-gaps/README.md", "\n".join(lines))
    write("industrial-case-studies/README.md",
          "# Industrial case studies\n\n"
          "None. No industrial case study has been located and verified for this repository, and none is "
          "invented here. A case study may be added only with a verified source and a statement of what "
          "the source does and does not report.\n\n"
          "Planned candidates (unverified, not searched): belt-conveyor speed control with variable "
          "payload; PMSM servo drives; level control in process tanks.\n")


def main():
    metas = R.load_metas()
    source_register(metas)
    algorithm_index()
    standards_register(metas)
    comparisons()
    reviews()
    gaps_and_cases()
    print("research written:", sum(1 for _ in OUT.rglob("*.md")), "files")


if __name__ == "__main__":
    main()
