def algorithm_index():
    lines = ["# Algorithm to source index\n",
             "Which algorithm in `src/control_lab` rests on which register entry. A source listed here "
             "supports the method's definition; the numbers in the notebooks come from the executed "
             "code, not from the source.\n",
             "| Algorithm | Sources (status) | Notebooks | Experiments |", "|---|---|---|---|"]
    for name, keys, nbs, exps in ALGOS:
        ks = "; ".join(f"{k} ({refs.status_tag(k)})" for k in keys)
        lines.append(f"| {name} | {ks} | {nbs} | {exps} |")
    write("algorithm-paper-index.md", "\n".join(lines))


def standards_register(metas):
    used = {k: [m["number"] for m in metas if k in m.get("standards", [])] for k in refs.STANDARDS}
    lines = ["# Standards register\n",
             "Standards are paid documents. For every entry below only the catalogue record was seen; "
             "no clause, formula or coefficient from a standard is used in the code.\n",
             "## Verified catalogue records\n",
             "| Key | Code | Title | Edition (published) | Notebooks | Relevance | Status note | Evidence |",
             "|---|---|---|---|---|---|---|---|"]
    for k, s in refs.STANDARDS.items():
        v = s["verification"]
        lines.append(f"| {k} | {s['body']} {s['code']} | {s['title']} | {s['edition']} ({s['published']}) | "
                     f"{', '.join(used[k]) or 'none'} | {s['relevance']} | {s['status_note']} | "
                     f"{v['status']}: {v['evidence_url']} - {v['note']} |")
    lines += ["\n## Named in the project brief, not verified\n",
              "| Item | Note |", "|---|---|"]
    for a, b in refs.UNVERIFIED_CANDIDATES:
        lines.append(f"| {a} | {b} |")
    write("standards-register.md", "\n".join(lines))


