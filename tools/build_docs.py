"""Generate docs/validation-status.md, docs/topic-taxonomy.md, docs/projects.md, docs/notebooks.md."""

from __future__ import annotations

import registry as R
import taxonomy

DOCS = R.ROOT / "docs"
HEAD = "<!-- Generated by tools/build_docs.py. Do not edit by hand. -->\n\n"

PROJECT_SECTIONS = [
    "Project overview", "Problem statement", "Engineering context", "Literature review",
    "System requirements", "System architecture", "Mathematical model", "Hardware and software design",
    "Dataset and measurement documentation", "Algorithm design", "Simulation", "Source code",
    "Physical implementation", "Experimental methodology", "Performance evaluation",
    "Results and visualization", "Failure analysis", "Limitations", "Engineering recommendations",
    "References",
]
# What a research notebook supplies for the 20-part project structure (author's assessment).
NOTEBOOK_PROVIDES = {
    "Project overview": "yes", "Problem statement": "yes", "Engineering context": "partial",
    "Literature review": "partial", "System requirements": "no", "System architecture": "partial",
    "Mathematical model": "yes", "Hardware and software design": "software only",
    "Dataset and measurement documentation": "synthetic or simulated only",
    "Algorithm design": "yes", "Simulation": "yes", "Source code": "yes (library)",
    "Physical implementation": "no", "Experimental methodology": "simulation only",
    "Performance evaluation": "yes", "Results and visualization": "yes", "Failure analysis": "partial",
    "Limitations": "yes", "Engineering recommendations": "partial", "References": "yes (see registers)",
}


def write(name, text):
    (DOCS / name).write_text(HEAD + text.rstrip() + "\n")


def validation_status(metas):
    rows = []
    n_ok = n_tot = 0
    for m in metas:
        exp = m["experiments"][0]
        res = R.load_result(exp)
        cs = R.checks_summary(res)
        rs = R.ref_summary(m)
        n_ok += cs["passed"]
        n_tot += cs["total"]
        rows.append(f"| {m['number']} | [{m['title']}](../{m['notebook']}) | {R.content_status(m)} | "
                    f"{cs['passed']}/{cs['total']} checks, {res['result_status']} | "
                    f"{rs['verified']} verified, {rs['partial']} partial | Not validated |")
    t = ("| No. | Notebook | Content | Simulation | Research | Hardware |\n|---|---|---|---|---|---|\n"
         + "\n".join(rows))
    write("validation-status.md", f"""# Validation status

Five dimensions are reported separately and never merged into one score.

| Dimension | Meaning here |
|---|---|
| Content | All 15 required sections are present in the notebook. Says nothing about quality. |
| Software | Library unit tests and executed notebooks passed on the build machine. GitHub Actions workflows are written but **have not been run**: the repository could not be pushed from the build environment. |
| Research | Reference records verified by web search of publisher or index pages. No full text was read. |
| Simulation | Automated checks of each executed notebook against an analytic or independent reference. |
| Hardware | No physical experiment, hardware-in-the-loop run or firmware exists. Every entry is **Not validated**. |

{t}

Totals: {len(metas)} notebooks, {n_ok} of {n_tot} automated checks passed. Hardware-validated items: 0.

What the checks do and do not show: a passing check means the code reproduced a closed form, a
conservation law or an independent solver within the stated tolerance. It does not mean the model
resembles a physical machine. All plant parameters are illustrative.
""")


def topic_doc():
    rows = taxonomy.topic_rows()
    counts = R.topic_counts(rows)
    out = ["# Topic taxonomy and coverage\n",
           "Status vocabulary: Planned, In Progress, Research Verified, Simulation Validated, Hardware "
           "Validated. Only the first, second and fourth occur; no topic has reached Research Verified "
           "as a topic-level status or Hardware Validated.\n",
           "A topic is *Simulation Validated* when a notebook treats it and its automated checks against "
           "an analytic or independent reference pass. *In Progress* means the topic appears inside "
           "another notebook or is covered only in part; the scope note says how. Everything else is "
           "*Planned* and has no content.\n",
           "Counts: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + f" (of {len(rows)}).\n"]
    for section in taxonomy.SECTIONS:
        sec = [r for r in rows if r["section"] == section]
        c = R.topic_counts(sec)
        out.append(f"## {section}\n")
        out.append(", ".join(f"{k}: {v}" for k, v in c.items()) + "\n")
        out.append("| Topic | Status | Notebooks | Scope note |\n|---|---|---|---|")
        for r in sec:
            out.append(f"| {r['topic']} | {r['status']} | {', '.join(r['notebooks']) or '-'} | {r['note'] or '-'} |")
        out.append("")
    write("topic-taxonomy.md", "\n".join(out))


def projects_doc(metas):
    nb = {m["number"]: m for m in metas}
    out = ["# Project catalog\n",
           "Fifteen end-to-end projects are defined. None is complete. The standard structure has 20 parts "
           "(overview through references). What exists for a project is a research notebook, which "
           "supplies the parts shown in the second table, and nothing else: no per-project folder, "
           "no embedded firmware and no physical build. Empty project folders are deliberately not "
           "created.\n",
           "| No. | Project | Status | Notebooks | What exists and what is missing |\n|---|---|---|---|---|"]
    for n, t, s, nbs, note in taxonomy.PROJECTS:
        links = ", ".join(f"[{x}](../{nb[x]['notebook']})" for x in nbs) or "-"
        out.append(f"| {n:02d} | {t} | {s} | {links} | {note} |")
    out += ["\nStatus counts: " + ", ".join(
        f"{k} {sum(1 for p in taxonomy.PROJECTS if p[2] == k)}" for k in ("In Progress", "Planned", "Blocked")),
        "\nProject 14 is Blocked: it needs real or public sensor recordings, and no such dataset has been "
        "located and verified. Synthetic recordings would not show that a fault detector works.\n",
        "## What a research notebook covers of the 20-part structure\n",
        "| Part | Covered by a notebook |\n|---|---|"]
    out += [f"| {i}. {p} | {NOTEBOOK_PROVIDES[p]} |" for i, p in enumerate(PROJECT_SECTIONS, 1)]
    write("projects.md", "\n".join(out))


def notebooks_doc(metas):
    out = ["# Notebook index\n",
           "| No. | Title | Difficulty (author's judgement) | Roadmap level | Experiment | Folder |\n"
           "|---|---|---|---|---|---|"]
    for m in metas:
        out.append(f"| {m['number']} | [{m['title']}](../{m['notebook']}) | {taxonomy.difficulty(m['level'])} | "
                   f"{taxonomy.NOTEBOOK_ROADMAP[m['number']]} {taxonomy.ROADMAP_LEVELS[taxonomy.NOTEBOOK_ROADMAP[m['number']]]} | "
                   f"`{m['experiments'][0]}` | `notebooks/{m['folder']}` |")
    write("notebooks.md", "\n".join(out))


def main():
    metas = R.load_metas()
    DOCS.mkdir(exist_ok=True)
    validation_status(metas)
    topic_doc()
    projects_doc(metas)
    notebooks_doc(metas)
    print("docs generated")


if __name__ == "__main__":
    main()
