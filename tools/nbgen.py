"""Notebook generator: turns a spec module into a 15-section .ipynb.

A spec module defines META (dict) and build() -> {section_number: [cell, ...]}. A cell is built
with md() or code(). Every notebook must supply all 15 sections of the open-control learning
module (section 4 receives an auto-generated reference table from tools/refs.py).
"""

from __future__ import annotations

import importlib
import textwrap
from pathlib import Path

import nbformat
import refs

ROOT = Path(__file__).resolve().parent.parent

SECTION_TITLES = {
    1: "Learning Objectives",
    2: "Real-World Engineering Problem",
    3: "Research Background",
    4: "Research Literature",
    5: "Mathematical Foundation",
    6: "System Modeling",
    7: "Dataset and Measurement Data",
    8: "Algorithm Architecture",
    9: "Algorithm Implementation",
    10: "Simulation and Numerical Analysis",
    11: "Experimental Validation",
    12: "Performance Evaluation",
    13: "Visualization and Interpretation",
    14: "Research Discussion and Limitations",
    15: "Summary, Exercises, and Further Research",
}


class Cell:
    def __init__(self, kind: str, text: str):
        self.kind, self.text = kind, textwrap.dedent(text).strip("\n")


def md(text: str) -> Cell:
    return Cell("md", text)


def code(text: str) -> Cell:
    return Cell("code", text)


def _status_cell(meta: dict) -> str:
    n_ref = len(meta.get("refs", [])) + len(meta.get("standards", []))
    rows = [
        ("Content", "All 15 sections written."),
        ("Software", "Executed from a clean kernel; library covered by unit tests."),
        ("Research", f"{n_ref} reference(s), verification status shown in section 4. "
                     "Recent literature (2020 onward) was not searched."),
        ("Simulation", "Executed. Results below were generated by this notebook."),
        ("Hardware", meta.get("hardware", "Not validated on hardware. No physical experiment "
                                          "was performed.")),
    ]
    table = "\n".join(f"| {a} | {b} |" for a, b in rows)
    return (f"# {meta['title']}\n\n"
            f"`{meta['id']}` | level {meta.get('level', 'n/a')} | "
            f"experiment id(s): {', '.join('`' + e + '`' for e in meta['experiments'])}\n\n"
            f"| Dimension | Status |\n|---|---|\n{table}\n\n"
            "All parameter values are illustrative and are not taken from a measured machine "
            "or plant unless a dataset section says so.")


def _refs_cell(keys: list[str], std_keys: list[str] | None = None) -> str:
    lines = ["### Reference table", "",
             "| Key | Citation | Role | Limitation | Verification |", "|---|---|---|---|---|"]
    for k in keys:
        r = refs.REFS[k]
        v = r["verification"]
        lines.append(f"| {k} | {refs.cite(k)} | {r['role']} | {r['limits']} | "
                     f"{v['status']} ({v['checked']}, {v['method']}). {v['note']} |")
    for k in std_keys or []:
        r = refs.STANDARDS[k]
        v = r["verification"]
        lines.append(f"| {k} | {r['body']} {r['code']}, {r['title']} (edition {r['edition']}, "
                     f"{r['published']}) | {r['relevance']} | {r['status_note']} | "
                     f"{v['status']} ({v['checked']}, {v['method']}). {v['note']} |")
    lines += ["",
              "Verification here means the bibliographic record was found on a publisher, index, "
              "library or author page. It does not mean the full text was read, and no "
              "numerical claim in this notebook is taken from these papers."]
    return "\n".join(lines)


def build_notebook(module_name: str) -> tuple[nbformat.NotebookNode, dict]:
    mod = importlib.import_module(f"specs.{module_name}")
    meta = mod.META
    sections = mod.build()
    missing = [n for n in SECTION_TITLES if n not in sections]
    if missing:
        raise ValueError(f"{module_name}: missing sections {missing}")
    nb = nbformat.v4.new_notebook()
    nb.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python",
                                 "name": "python3"}
    nb.metadata["open_control"] = {"id": meta["id"], "experiments": meta["experiments"]}
    cells = [nbformat.v4.new_markdown_cell(_status_cell(meta))]
    cells.append(nbformat.v4.new_code_cell(
        "import numpy as np\nimport matplotlib.pyplot as plt\n"
        "import control_lab\nplt.rcParams.update({'figure.dpi': 100, 'axes.grid': True})\n"
        "print('control_lab', control_lab.__version__)"))
    for n, title in SECTION_TITLES.items():
        cells.append(nbformat.v4.new_markdown_cell(f"## {n}. {title}"))
        for c in sections[n]:
            cells.append(nbformat.v4.new_markdown_cell(c.text) if c.kind == "md"
                         else nbformat.v4.new_code_cell(c.text))
        if n == 4:
            cells.append(nbformat.v4.new_markdown_cell(_refs_cell(meta["refs"], meta.get("standards"))))
    nb.cells = cells
    return nb, meta


def write_notebook(module_name: str) -> Path:
    nb, meta = build_notebook(module_name)
    out = ROOT / "notebooks" / meta["folder"]
    out.mkdir(parents=True, exist_ok=True)
    path = out / f"{meta['id']}.ipynb"
    nbformat.write(nb, path)
    return path
